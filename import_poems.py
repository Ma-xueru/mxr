def gen_pinyin(text):
    lines = []
    for line in text.split('\n'):
        chars = []
        for ch in line:
            if '一' <= ch <= '鿿':
                chars.append(pinyin(ch, style=Style.TONE)[0][0])
            else:
                chars.append(ch)
        lines.append(''.join(chars))
    return '\n'.join(lines)

