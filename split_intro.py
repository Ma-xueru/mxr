count = 0
for row in rows:
    parts = row.split('\t', 3)
    if len(parts) < 4: continue
    pid, title, grade, intro = parts[0], parts[1], parts[2], parts[3]

    # Parse existing intro to extract author, annotations, translation
    author_name = ''
    annotations = ''
    translation = ''

    # Pattern: "（唐）李白代表作。\n注释：...\n译文：..."
    # Extract author
    am = re.match(r'[（(]([^）)]+)[）)]\s*(\S+)', intro)
    if am:
        author_name = am.group(2)  # e.g. "李白"
    elif re.match(r'^[一-鿿]{2,4}$', title[:2]):
        # Try to extract from intro start
        am2 = re.match(r'([一-鿿]{2,4})(所作|名篇|名作|代表作|的)', intro)
        if am2:
            author_name = am2.group(1)

    # Extract annotations
    anno_match = re.search(r'注释[：:](.*?)(?:译文[：:]|翻译[：:]|$)', intro, re.DOTALL)
    if anno_match:
        annotations = anno_match.group(1).strip()

    # Extract translation
    trans_match = re.search(r'(?:译文|翻译)[：:](.*?)$', intro, re.DOTALL)
    if trans_match:
        translation = trans_match.group(1).strip()

    # Get background
    bg = backgrounds.get(title, f"{grade}必学古诗。")

    # Escape for SQL
    esc = lambda s: s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    sql = (f"UPDATE course SET author_name='{esc(author_name)}', "
           f"annotations='{esc(annotations)}', "
           f"translation='{esc(translation)}', "
           f"intro='{esc(bg)}' "
           f"WHERE id={pid};")
    with open('tmp_split.sql', 'w', encoding='utf-8') as f:
        f.write(sql)
    subprocess.run(mysql + ' < tmp_split.sql', shell=True, capture_output=True)
    count += 1

print(f"Updated {count} poems")
