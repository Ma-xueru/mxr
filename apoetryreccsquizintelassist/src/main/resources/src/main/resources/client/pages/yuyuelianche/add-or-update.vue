    import xiaEditor from '@/components/xia-editor/xia-editor';
    import multipleSelect from "@/components/momo-multipleSelect/momo-multipleSelect";
	export default {
		data() {
			return {
				cross:'',
				ruleForm: {
				studentaccount: '',
				studentname: '',
				reservetime: '',
				teacheraccount: '',
				teachername: '',
			        reservestatus: '已预约',
			        sfsh: '待审核',
				shhf: '',
				reservecount: '',
				},
				reservestatusOptions: [],
				reservestatusIndex: 0,
				// 登录用户信息
				user: {},
                ro:{
                   studentaccount : false,
                   studentname : false,
                   reservetime : false,
                   teacheraccount : false,
                   teachername : false,
                   reservestatus : false,
                   sfsh : false,
                   shhf : false,
                   reservecount : false,
                },
			}
		},
		components: {
			wPicker,
            xiaEditor,
            multipleSelect
		},
		watch:{
		},
		async onLoad(options) {
			let table = uni.getStorageSync("nowTable");
			// 获取用户信息
			let res = await this.$api.session(table);
			this.user = res.data;
			
			// ss读取
			this.ruleForm.studentaccount = this.user.studentaccount
			this.ro.studentaccount = true;
			this.ruleForm.studentname = this.user.studentname
			this.ro.studentname = true;


			// 自定义下拉框值
			this.reservestatusOptions = "已取消,已预约".split(',')

			// 如果有登录，获取登录后保存的userid
			this.ruleForm.userid = uni.getStorageSync("userid")
			if (options.refid) {
				// 如果上一级页面传递了refid，获取改refid数据信息
				this.ruleForm.refid = options.refid;
				this.ruleForm.nickname = uni.getStorageSync("nickname");
			}
			// 如果是更新操作
			if (options.id) {
				this.ruleForm.id = options.id;
				// 获取信息
				res = await this.$api.info(`coursereserve`, this.ruleForm.id);
				this.ruleForm = res.data;
			}
			// 跨表
			this.cross = options.cross;
			if(options.cross){
				var obj = uni.getStorageSync('crossObj');
				for (var o in obj){
					if(o=='studentaccount'){
					this.ruleForm.studentaccount = obj[o];
					this.ro.studentaccount = true;
					continue;
					}
					if(o=='studentname'){
					this.ruleForm.studentname = obj[o];
					this.ro.studentname = true;
					continue;
					}
					if(o=='reservetime'){
					this.ruleForm.reservetime = obj[o];
					this.ro.reservetime = true;
					continue;
					}
					if(o=='teacheraccount'){
					this.ruleForm.teacheraccount = obj[o];
					this.ro.teacheraccount = true;
					continue;
					}
					if(o=='teachername'){
					this.ruleForm.teachername = obj[o];
					this.ro.teachername = true;
					continue;
					}
					if(o=='reservestatus'){
					this.ruleForm.reservestatus = obj[o];
					this.ro.reservestatus = true;
					continue;
					}
					if(o=='reservecount'){
					this.ruleForm.reservecount = obj[o];
					this.ro.reservecount = true;
					continue;
					}
				}
            this.ruleForm.reservecount = 0;
            this.ro.reservecount = false;
			}
			this.styleChange()
            this.$forceUpdate()
		},
		computed: {
			baseUrl() {
				return this.$base.url;
			},
		},
		methods: {
			styleChange() {
				this.$nextTick(()=>{
					document.querySelectorAll('.radioText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.radioTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666"}
