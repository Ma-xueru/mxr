<script>
    import multipleSelect from "@/components/momo-multipleSelect/momo-multipleSelect";
	export default {
		data() {
			return {
				ruleForm: {
				},
				tableName:"",
				studentgenderOptions: [],
				studentgenderIndex: 0,
				teachergenderOptions: [],
				teachergenderIndex: 0,
			}
		},
        components: {
            multipleSelect
        },
		computed: {
			baseUrl() {
				return this.$base.url;
			}
		},
		async onLoad() {
			let table = uni.getStorageSync("nowTable");
			let res = await this.$api.session(table);
			this.ruleForm = res.data;
			this.tableName = table;
			// 自定义下拉框值
			if(this.tableName=='student'){
				this.studentgenderOptions = "男,女".split(',');
				this.studentgenderOptions.forEach((item, index) => {
					if(item==this.ruleForm.gender) {
						this.studentgenderIndex = index;
					}
				});
			}
			// 自定义下拉框值
			if(this.tableName=='teacher'){
				this.teachergenderOptions = "男,女".split(',');
				this.teachergenderOptions.forEach((item, index) => {
					if(item==this.ruleForm.gender) {
						this.teachergenderIndex = index;
					}
				});
			}
			this.styleChange()
            this.$forceUpdate()
		},
		methods: {
			studentavatarTap() {
				let _this = this;
				this.$api.upload(function(res) {
					_this.ruleForm.avatar = 'file/' + res.file;
					_this.$forceUpdate();
				});
			},
            // 下拉变化
            studentgenderChange(e) {
                    this.studentgenderIndex = e.target.value
                    this.ruleForm.gender = this.studentgenderOptions[this.studentgenderIndex]
            },
			teacherzhaopianTap() {
				let _this = this;
				this.$api.upload(function(res) {
					_this.ruleForm.zhaopian = 'file/' + res.file;
					_this.$forceUpdate();
				});
			},
            // 下拉变化
            teachergenderChange(e) {
                    this.teachergenderIndex = e.target.value
                    this.ruleForm.gender = this.teachergenderOptions[this.teachergenderIndex]
            },

            toggleTab(str) {
                this.$refs[str].show();
            },

			styleChange() {
				this.$nextTick(()=>{
					document.querySelectorAll('.radioText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.radioTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#333"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#333"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.uni-radio-input').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"border":"2rpx solid #999999","borderRadius":"0","background":"#ffffff"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.uni-radio-input-checked').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"border":"2rpx solid #5fb959","borderRadius":"0","color":"#fff","background":"#5fb959"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.uni-checkbox-input').forEach(el => {
					  el.removeAttribute('style')
