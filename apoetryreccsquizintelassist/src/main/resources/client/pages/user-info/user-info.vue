						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.uni-checkbox-input-checked').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"border":"2rpx solid #5fb959","color":"#fff","borderRadius":"0","background":"#5fb959"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
				})
			},
			// 获取uuid
			getUUID () {
				return new Date().getTime();
			},
			logout() {
				uni.clearStorageSync()
				uni.reLaunch({
					url:'/pages/index/index'
				})
			},
			
			// 注册
			async update() {
				if((!this.ruleForm.studentaccount) && `student` == this.tableName){
					this.$utils.msg(`用户账号不能为空`);
					return
				}
				if((!this.ruleForm.studentpassword) && `student` == this.tableName){
					this.$utils.msg(`用户密码不能为空`);
					return
				}
				if((!this.ruleForm.studentname) && `student` == this.tableName){
					this.$utils.msg(`用户姓名不能为空`);
					return
				}
				if(`student` == this.tableName && this.ruleForm.telephone&&(!this.$validate.isMobile(this.ruleForm.telephone))){
					this.$utils.msg(`手机号码应输入手机格式`);
					return
				}
				if((!this.ruleForm.teacheraccount) && `teacher` == this.tableName){
					this.$utils.msg(`教师账号不能为空`);
					return
				}
				if((!this.ruleForm.teacherpassword) && `teacher` == this.tableName){
					this.$utils.msg(`教师密码不能为空`);
					return
				}
				if((!this.ruleForm.teachername) && `teacher` == this.tableName){
					this.$utils.msg(`教师姓名不能为空`);
					return
				}
				if(`teacher` == this.tableName && this.ruleForm.lianxidianhua&&(!this.$validate.isMobile(this.ruleForm.lianxidianhua))){
					this.$utils.msg(`联系电话应输入手机格式`);
					return
				}
				if(`teacher` == this.tableName && this.ruleForm.reservecount&&(!this.$validate.isIntNumer(this.ruleForm.reservecount))){
					this.$utils.msg(`可约人数应输入整数`);
					return
				}
				let table = uni.getStorageSync("nowTable");
				await this.$api.update(table, this.ruleForm);
				this.$utils.msgBack('修改成功');;
			},

		}
	}
